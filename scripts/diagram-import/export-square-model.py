#!/usr/bin/env python3
"""Writes a trained square classifier as packages/types/src/diagram-square-model.ts.

    python scripts/diagram-import/export-square-model.py <model.pt>

Weights are stored as one signed byte each (per-layer scale), which is what keeps the
model small enough to ship inside the shared package. Also writes parity vectors the
API's Jest suite checks, so the TypeScript forward pass stays equal to PyTorch's.
Needs numpy and torch; see train-square-classifier.py.
"""

import base64
import json
import sys
from pathlib import Path

import numpy as np
import torch
import torch.nn.functional as F

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "packages/types/src/diagram-square-model.ts"
PARITY = ROOT / "apps/api/src/common/chess/__fixtures__/diagram/square-model-parity.json"
CLASSES = ".KQRBNPkqrbnp"
SIZE = 32


def quantize(tensor: torch.Tensor) -> tuple[dict, torch.Tensor]:
    values = tensor.detach().numpy()
    scale = float(np.abs(values).max()) / 127
    ints = np.clip(np.round(values / scale), -127, 127).astype(np.int8)
    packed = {"data": base64.b64encode(ints.tobytes()).decode(), "scale": round(scale, 8)}
    return packed, torch.tensor(ints.astype(np.float32) * round(scale, 8))


def main() -> None:
    state = torch.load(sys.argv[1], map_location="cpu", weights_only=True)
    quantized: dict[str, torch.Tensor] = {}
    layers: dict[str, dict] = {}
    for name in ["c1", "c2", "c3", "f1", "f2"]:
        packed, weights = quantize(state[f"{name}.weight"])
        bias = state[f"{name}.bias"]
        quantized[f"{name}.weight"] = weights
        quantized[f"{name}.bias"] = bias.float()
        layers[name] = {
            "bias": [round(float(v), 5) for v in bias],
            "inputs": int(weights.shape[1]),
            "outputs": int(weights.shape[0]),
            "weights": packed,
        }

    def forward(x: torch.Tensor) -> torch.Tensor:
        x = (x - 0.5) * 2
        for name in ["c1", "c2", "c3"]:
            x = F.conv2d(x, quantized[f"{name}.weight"], torch.tensor([round(float(v), 5) for v in quantized[f"{name}.bias"]]), padding=1)
            x = F.max_pool2d(F.relu(x), 2)
        x = x.flatten(1)
        bias = torch.tensor([round(float(v), 5) for v in quantized["f1.bias"]])
        x = F.relu(x @ quantized["f1.weight"].T + bias)
        bias = torch.tensor([round(float(v), 5) for v in quantized["f2.bias"]])
        return (x @ quantized["f2.weight"].T + bias).softmax(1)

    source = [
        "// Generated by scripts/diagram-import/export-square-model.py. Do not edit.",
        "//",
        "// The weights of the square classifier in diagram-square-classifier.ts, one signed",
        "// byte each. Trained by scripts/diagram-import/train-square-classifier.py.",
        "",
        "export type DiagramModelTensor = { data: string; scale: number };",
        "export type DiagramModelLayer = { bias: number[]; inputs: number; outputs: number; weights: DiagramModelTensor };",
        "",
        "export const DIAGRAM_SQUARE_MODEL: {",
        "  classes: string;",
        "  convs: DiagramModelLayer[];",
        "  dense: DiagramModelLayer[];",
        "  size: number;",
        "} = " + json.dumps({"classes": CLASSES, "convs": [layers["c1"], layers["c2"], layers["c3"]], "dense": [layers["f1"], layers["f2"]], "size": SIZE}) + ";",
        "",
    ]
    OUT.write_text("\n".join(source), encoding="utf8")

    rng = np.random.default_rng(1)
    patches = rng.random((3, 1, SIZE, SIZE), dtype=np.float32)
    patches[1] = 1.0
    with torch.no_grad():
        probabilities = forward(torch.tensor(patches)).numpy()
    PARITY.write_text(
        json.dumps({"patches": [[round(float(v), 5) for v in p.flatten()] for p in patches], "probabilities": [[round(float(v), 5) for v in p] for p in probabilities]}),
        encoding="utf8",
    )
    print(f"{OUT.relative_to(ROOT)}: {OUT.stat().st_size} bytes")


if __name__ == "__main__":
    main()
